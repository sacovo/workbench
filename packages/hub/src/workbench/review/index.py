"""review/INDEX.md: every item on one line, grouped by whose move it is.

Generated from the item files after every write and by `wbench index`; never edited by hand. The text
depends only on the items (no generation time), so regenerating an unchanged store leaves the
file byte for byte the same, and a delivery to the agent does not change it.
"""

from __future__ import annotations

GROUPS = (
    ("running", "Running jobs"),
    ("waiting_owner", "Owner's move"),
    ("waiting_agent", "Agent's move"),
    ("done", "Done"),
    ("dropped", "Dropped"),
)


def item_line(state: dict) -> str:
    details = []
    questions = state.get("questions") or []
    if questions:
        details.append(f"{len(state['open_questions'])} of {len(questions)} questions open")
    if state["kind"] == "measurement":
        details.append(f"{state['quantity']} in {state['unit']}")
    last = state["last_activity"]
    details.append(f"last by {last['role']} {last['at'][:16].replace('T', ' ')}")
    return f"- [{state['id']}]({state['id']}.yaml) {state['kind']}: {state['title']} ({'; '.join(details)})"


def render_index(states: list[dict], unreadable: list[tuple[str, str]]) -> str:
    """`states` from fold(); `unreadable` as (file name, error) for items that failed to load."""
    lines = [
        "# Review items",
        "",
        "Generated by `wbench index` from the item files in this directory; do not edit.",
    ]
    for status, heading in GROUPS:
        group = [s for s in states if s["status"] == status]
        if status == "running" and not group:
            continue  # only while a job runs, so projects without jobs keep their index unchanged
        lines += ["", f"## {heading} ({len(group)})"]
        if group:
            lines.append("")
            lines += [item_line(s) for s in group]
    if unreadable:
        lines += ["", f"## Unreadable ({len(unreadable)})", ""]
        lines += [f"- {name}: {error.splitlines()[0] if error else ''}" for name, error in unreadable]
    return "\n".join(lines) + "\n"
