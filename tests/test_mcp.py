"""The MCP shim end to end, over stdio, with the SDK's own client (mcp.ClientSession): lists its
tools from the registry's own schemas, runs local operations (status, ask, inbox) and forwards a
needs_hub one (show) to a running hub with the fake kernel. `python -m workbench mcp` is the exact
command plugin/.mcp.json uses (with the plugin's own interpreter in place of sys.executable)."""

from __future__ import annotations

import json
import os
import sys

import anyio
from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client
from mcp_types import CallToolResult

from hub_helpers import project  # noqa: F401  (fixture)
from hub_running import RunningHub
from workbench.mcp import TOOL_NAMES
from workbench.project import write_hub_info


def _env(**extra: str) -> dict:
    return {**{k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV"}, **extra}


def _params(cwd: str, **extra_env: str) -> StdioServerParameters:
    return StdioServerParameters(command=sys.executable, args=["-m", "workbench", "mcp"], cwd=cwd, env=_env(**extra_env))


def _text(result: CallToolResult) -> str:
    assert len(result.content) == 1 and result.content[0].type == "text", result.content
    return result.content[0].text


def test_list_tools_matches_the_curated_registry_subset(project):
    async def go():
        async with stdio_client(_params(str(project.root))) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                listed = await session.list_tools()
                assert [t.name for t in listed.tools] == list(TOOL_NAMES)
                # Schemas are generated by the registry, never hand-written in the shim.
                for t in listed.tools:
                    assert t.input_schema["type"] == "object"
                    assert t.input_schema["additionalProperties"] is False
                    assert t.description  # every tool has a non-empty description
                for name in ("answer", "comment", "serve", "open", "mcp", "doctor", "snapshot", "set-status", "attach", "link", "index"):
                    assert name not in {t.name for t in listed.tools}

    anyio.run(go)


def test_call_status_then_ask_then_inbox(project):
    async def go():
        async with stdio_client(_params(str(project.root))) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()

                status = await session.call_tool("status", {})
                assert status.is_error is False
                state = json.loads(_text(status))
                assert state["project"]["name"] == project.name
                assert state["project"]["root"] == str(project.root)

                questions = [{"id": "q1", "text": "Which front limit?", "options": [{"id": "a", "label": "35 mm"}]}]
                asked = await session.call_tool("ask", {"title": "Front limit", "questions": questions})
                assert asked.is_error is False
                opened = json.loads(_text(asked))
                assert (opened["id"], opened["kind"], opened["status"]) == ("R-0001", "decision", "waiting_owner")
                assert (project.root / "review" / "R-0001.yaml").is_file()

                # The agent's own decision is not an owner event: nothing for it to pull yet.
                inbox = await session.call_tool("inbox", {})
                assert inbox.is_error is False
                assert json.loads(_text(inbox))["items"] == []

                # A bad call becomes a tool error carrying the real message, not a dropped session
                # or a generic "Internal server error".
                missing = await session.call_tool("item", {"id": "R-0099"})
                assert missing.is_error is True and "no item R-0099" in _text(missing)

                bad_args = await session.call_tool("note", {"kind": "nonsense", "title": "x"})
                assert bad_args.is_error is True and "argument kind" in _text(bad_args)

    anyio.run(go)


def test_the_project_is_found_from_claude_project_dir_when_elsewhere(project, tmp_path):
    async def go():
        params = _params(str(tmp_path), CLAUDE_PROJECT_DIR=str(project.root))
        async with stdio_client(params) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                status = await session.call_tool("status", {})
                assert status.is_error is False
                assert json.loads(_text(status))["project"]["root"] == str(project.root)

    anyio.run(go)


def test_a_needs_hub_tool_is_forwarded_to_the_running_hub_with_the_fake_kernel(project):
    hub = RunningHub(project)
    write_hub_info(project, port=hub.port, token=hub.token)  # RunningHub itself only serves sockets
    try:
        async def go():
            async with stdio_client(_params(str(project.root))) as (read, write):
                async with ClientSession(read, write) as session:
                    await session.initialize()
                    shown = await session.call_tool("show", {"assembly": "demo"})
                    assert shown.is_error is False
                    result = json.loads(_text(shown))
                    assert result["assembly"] == "demo" and result["parts"] == ["base", "column", "carriage"]
                    assert result["generation"] == 1  # answered by the fake kernel RunningHub already started

                    status = await session.call_tool("status", {})
                    assert json.loads(_text(status))["hub"]["running"] is True

        anyio.run(go)
    finally:
        hub.stop()
